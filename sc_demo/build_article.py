d.h2("4.7　结论")
d.p("在人类 DRG 中，用于解释针刺镇痛的分子靶点并不共享同一水平的亚型选择性。"
    "Nav1.8、Nav1.9、P2X3 与阿片受体可作为亚型限定性靶点；A1R 不能——它在三名供体间给不出"
    "一致的富集类型；CB1 居中且稳定。"
    "“腺苷—A1R”通路在人类更可能作用于外周末梢或局部微环境，而非特定亚型胞体。"
    "跨物种比较显示这一格局在 Nav1.8、Nav1.9、P2X3 上保守，在 TRPV1 上分歧；"
    "A1R 则在两侧都未进入前十分之一（人类 22.7、小鼠 79.4 百分位），与“保守的亚型偏好”不符。"
    "更一般地，靶点能否做到亚型选择性，取决于配体、受体与效应器是否在同一批细胞内凑齐，"
    "而不只取决于受体表达多少：通道类靶点无须配体而可精准，GPCR 类则被配体分布绑死。"
    "对机制研究而言，这意味着引用啮齿类的亚型定位结论去解释人类针刺效应时需要更谨慎；"
    "对参数研究而言，这意味着应把“局部递质池”而非“纤维类型选择性”作为核心变量。")

