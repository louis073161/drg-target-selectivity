d.h2("3.12　检出能力的边界：注入模拟")
d.p("阴性结论必须交代它排除了什么、没有排除什么。为此做一个注入模拟：保留 A1R 的检出率"
    "（39.7%）与阳性细胞的表达量分布，只把阳性细胞在 13 个类型之间的归属按预设倍数向 hNP1 "
    "集中，再用同一函数重算 maxΔAUC 与百分位，每个倍数重复 200 次。观测值在这一实现下复现为"
    "0.115（P51.7），与主分析的 0.117（P52.4）相差 0.002，说明模拟与主管线同构。")
d.p("结果给出一条清晰的界线：富集 1.5 倍时 maxΔAUC 中位 0.148（P66）、2 倍时 0.278（P92），"
    "二者都不会被判为选择性；3 倍时 0.356（P97），200 次全部落入前 5%。换言之，本数据能可靠"
    "排除的是「A1R 在某一伤害感受器类型中接近饱和」这一强形式，2 倍上下的中等富集既不能证实、"
    "也不能排除。这一界线与 3.10 节等效性检验的结论一致（可排除强选择性，不能排除轻度偏移），"
    "但现在有了具体倍数。它也说明本文的措辞为何始终是「缺乏可重复的亚型偏好」而非「完全没有"
    "亚型偏好」：前者由供体间与跨队列的不一致支持，后者超出本数据的检出能力。")
d.p("需要同时指出，这一检出水平并不妨碍强选择性的出现。δ 阿片受体的检出率（41.1%）与 A1R"
    "（39.7%）几乎相同，其 maxΔAUC 达 0.335（匹配百分位 96.5）。因此「A1R 低表达所以测不出」"
    "这一辩解不能成立：同样的稀疏程度下，本流程足以把 δ 阿片受体送到右尾。二者的差别在于"
    "阳性细胞是否集中在同一类型，而不在于检测灵敏度。")

